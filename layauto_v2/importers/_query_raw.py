"""Complete-consumption parser for the declared synthetic query text grammar."""
from __future__ import annotations

import re
from dataclasses import dataclass
from fractions import Fraction
from typing import NoReturn

from layauto_v2.domain.codec import FrozenMap, freeze_map
from layauto_v2.domain.evidence import SourceFile
from layauto_v2.domain.results import Category, InputError

_IDENTIFIER = re.compile(r'[A-Za-z_][A-Za-z0-9_]*\Z')
_INTEGER = re.compile(r'(?:0|-?[1-9][0-9]*)\Z')


@dataclass(frozen=True)
class Text:
    source: SourceFile
    lines: tuple[str, ...]

    @classmethod
    def read(cls, source: SourceFile, max_bytes: int) -> Text:
        if len(source.data) > max_bytes:
            raise InputError('parse', 'InputSizeLimit', f'text exceeds {max_bytes} bytes', source.ref())
        try:
            text = source.data.decode('ascii')
        except UnicodeDecodeError as exc:
            raise InputError('parse', 'RawEncoding', 'query dialect requires ASCII', source.ref(byte_offset=exc.start)) from exc
        if not text.endswith('\n') or '\r' in text or any(ord(char) < 32 and char not in ('\t', '\n') for char in text):
            raise InputError('parse', 'RawEncoding', 'query dialect requires LF and final LF', source.ref())
        lines = tuple(text[:-1].split('\n'))
        for index, line in enumerate(lines):
            if not line or line.strip() != line:
                raise InputError('parse', 'RawEncoding', 'blank or padded query record', source.ref(line=index + 1))
        return cls(source, lines)

    def fail(self, code: str, message: str, index: int = 0, category: Category = 'parse') -> NoReturn:
        raise InputError(category, code, message, self.source.ref(line=index + 1))

    def location(self, index: int, token: int | None = None) -> FrozenMap:
        line = self.lines[index]
        return freeze_map({'path': self.source.uri, 'sha256': self.source.sha256,
                           'line_1based': index + 1, 'token_0based': token,
                           'lexeme': line if token is None else line.split()[token]})

    def require(self, index: int, expected: str, code: str) -> None:
        if index >= len(self.lines) or self.lines[index] != expected:
            self.fail(code, f'expected {expected!r}', min(index, len(self.lines) - 1))


def identifier(text: Text, token: str, index: int) -> str:
    if not _IDENTIFIER.fullmatch(token):
        text.fail('InvalidIdentity', f'unsupported identifier {token!r}', index)
    return token


def unsigned(text: Text, token: str, index: int, code: str = 'InvalidCount') -> int:
    if not token.isascii() or not token.isdecimal() or (len(token) > 1 and token[0] == '0'):
        text.fail(code, f'expected unsigned integer, got {token!r}', index)
    try:
        return int(token)
    except ValueError as exc:
        raise InputError('parse', code, 'integer exceeds interpreter digit limit', text.source.ref(line=index + 1)) from exc


@dataclass(frozen=True)
class XrefRow:
    layout: str
    source: str
    swapped: bool
    line: int


@dataclass(frozen=True)
class Xref:
    text: Text
    layout_top: str
    source_top: str
    layout_pin_count: int
    source_pin_count: int
    rows: tuple[XrefRow, ...]


def parse_xref(text: Text, kind: str, max_records: int) -> Xref:
    title, abbreviation = ('Instance', 'ixf') if kind == 'instance' else ('Net', 'nxf')
    text.require(0, f'# SVDB: {title} Cross Reference ({abbreviation}) (File format 1)', 'XrefHeader')
    if len(text.lines) < 8:
        text.fail('XrefHeader', 'incomplete xref header')
    prefixes = ('# SVDB: Layout Primary ', '# SVDB: Source Primary ')
    tops: list[str] = []
    for index, prefix in enumerate(prefixes, 1):
        if not text.lines[index].startswith(prefix):
            text.fail('XrefHeader', f'missing {prefix}', index)
        tops.append(identifier(text, text.lines[index][len(prefix):], index))
    text.require(3, '# SVDB: Layout system: GDSII', 'XrefHeader')
    text.require(4, '# SVDB: Source system: SPICE', 'XrefHeader')
    text.require(5, '# SVDB: Generated by Calibre LVS (synthetic fixture; not executed)', 'XrefHeader')
    text.require(6, '# SVDB: End of header.', 'XrefHeader')
    summary = text.lines[7].split()
    if kind == 'net':
        if not summary or summary.pop(0) != '%':
            text.fail('XrefSummary', 'net xref requires % summary prefix', 7)
    if len(summary) != 4:
        text.fail('XrefSummary', 'expected two top/pin-count pairs', 7)
    if summary[0] != tops[0] or summary[2] != tops[1]:
        text.fail('TopBindingMismatch', 'xref summary disagrees with its header', 7, 'binding')
    counts = (unsigned(text, summary[1], 7), unsigned(text, summary[3], 7))
    if len(text.lines) - 8 > max_records:
        text.fail('RecordLimit', f'xref exceeds {max_records} rows', 8)
    rows: list[XrefRow] = []
    seen: set[str] = set()
    for index in range(8, len(text.lines)):
        tokens = text.lines[index].split()
        if len(tokens) not in ((4, 5) if kind == 'instance' else (4,)):
            text.fail('InvalidXrefRecord', 'invalid xref column count', index)
        if tokens[0] != '0' or tokens[2] != '0':
            text.fail('UnsupportedNamespace', 'only flat namespace index zero is supported', index, 'unsupported')
        layout, source = identifier(text, tokens[1], index), identifier(text, tokens[3], index)
        if layout in seen:
            text.fail('DuplicateQueryIdentity', f'duplicate layout identity {layout}', index)
        seen.add(layout)
        swapped = len(tokens) == 5
        if swapped and tokens[4] != 'X':
            text.fail('UnsupportedSwapToken', 'only optional X is supported', index, 'unsupported')
        rows.append(XrefRow(layout, source, swapped, index))
    return Xref(text, tops[0], tops[1], counts[0], counts[1], tuple(rows))


@dataclass(frozen=True)
class NetNames:
    text: Text
    names: tuple[str, ...]
    opener: str
    timestamp: str


def parse_net_names(text: Text, max_records: int) -> NetNames:
    if text.lines[-1] != 'END OF RESPONSE':
        text.fail('MissingTerminator', 'NET NAMES must terminate at END OF RESPONSE', len(text.lines) - 1)
    text.require(0, 'Net_Names 20000', 'InvalidNetNamesHeader')
    text.require(1, 'Nets:', 'InvalidNetNamesHeader')
    if len(text.lines) < 4:
        text.fail('InvalidNetNamesHeader', 'NET NAMES count header missing')
    fields = text.lines[2].split(maxsplit=3)
    if len(fields) != 4 or fields[:2] != ['0', '0']:
        text.fail('InvalidNetNamesHeader', 'expected 0 0 count timestamp', 2)
    count = unsigned(text, fields[2], 2)
    if count != len(text.lines) - 4:
        text.fail('CountMismatch', 'NET NAMES count disagrees with consumed name rows', 2)
    if count > max_records:
        text.fail('RecordLimit', f'NET NAMES exceeds {max_records} rows', 2)
    names = tuple(identifier(text, name, index) for index, name in enumerate(text.lines[3:-1], 3))
    if len(set(names)) != len(names):
        text.fail('DuplicateNetName', 'NET NAMES contains duplicate names', 3)
    return NetNames(text, names, text.lines[0].split()[1], fields[3])


@dataclass(frozen=True)
class Polygon:
    layer: str
    layer_line: int
    section_line: int
    vertex_line: int
    points: tuple[tuple[int, int], ...]
    vertices: tuple[tuple[Fraction, Fraction], ...]


@dataclass(frozen=True)
class Response:
    text: Text
    precision: int
    metadata_lines: tuple[int, ...]
    polygons: tuple[Polygon, ...]
    timestamp: str


def parse_response(text: Text, kind: str, precision: int, tick_nm: Fraction,
                   max_records: int) -> Response:
    if text.lines[-1] != 'END OF RESPONSE':
        text.fail('MissingTerminator', 'query response must terminate at END OF RESPONSE', len(text.lines) - 1)
    opener = text.lines[0].split()
    expected = 'Device_Info' if kind == 'device_regions' else 'Net_Shapes'
    if len(opener) != 2 or opener[0] != expected:
        text.fail('DialectDrift', f'expected {expected} precision')
    actual_precision = unsigned(text, opener[1], 0, 'UnitBindingMismatch')
    if actual_precision != precision or actual_precision <= 0:
        text.fail('UnitBindingMismatch', 'response precision disagrees with bound dialect', 0, 'binding')
    text.require(1, 'Info:', 'ResponseHeader')
    if len(text.lines) < 4:
        text.fail('ResponseHeader', 'response count header missing')
    fields = text.lines[2].split(maxsplit=3)
    if len(fields) != 4 or fields[:2] != ['0', '0']:
        text.fail('ResponseHeader', 'expected 0 0 metadata-count timestamp', 2)
    count = unsigned(text, fields[2], 2)
    if count != (2 if kind == 'device_regions' else 1):
        text.fail('MetadataCountMismatch', 'metadata count unsupported by declared response kind', 2)
    if len(text.lines) <= 3 + count:
        text.fail('MetadataCountMismatch', 'truncated metadata', 2)
    if kind == 'device_regions':
        unsigned(text, text.lines[3], 3, 'DeviceMetadataDrift')
    metadata_lines = tuple(range(3, 3 + count))
    index = 2 + count
    polygons: list[Polygon] = []
    while index < len(text.lines) - 1:
        if len(polygons) >= max_records:
            text.fail('RecordLimit', f'response exceeds {max_records} polygons', index)
        layer = identifier(text, text.lines[index], index)
        if index + 7 > len(text.lines) - 1:
            text.fail('TruncatedPolygon', 'incomplete polygon section', index)
        section = text.lines[index + 1].split(maxsplit=3)
        if len(section) != 4 or section[:3] != ['1', '1', '0']:
            text.fail('OpaqueSectionHeaderDrift', 'unsupported opaque section tuple', index + 1)
        geometry = text.lines[index + 2].split()
        if not geometry or geometry[0] != 'p':
            text.fail('UnsupportedGeometryToken', 'only polygon geometry token p is supported', index + 2, 'unsupported')
        if geometry != ['p', '1', '4']:
            text.fail('UnsupportedPolygon', 'only one four-vertex polygon is supported', index + 2, 'unsupported')
        points: list[tuple[int, int]] = []
        for line_index in range(index + 3, index + 7):
            tokens = text.lines[line_index].split()
            if len(tokens) != 2 or any(_INTEGER.fullmatch(token) is None for token in tokens):
                text.fail('InvalidCoordinate', 'expected exact integer y x coordinate pair', line_index)
            try:
                y, x = int(tokens[0]), int(tokens[1])
            except ValueError as exc:
                raise InputError('parse', 'InvalidCoordinate', 'integer exceeds interpreter digit limit', text.source.ref(line=line_index + 1)) from exc
            points.append((x, y))
        xs, ys = {x for x, _ in points}, {y for _, y in points}
        if len(set(points)) != 4 or len(xs) != 2 or len(ys) != 2 or any(
            (points[i][0] == points[(i + 1) % 4][0]) == (points[i][1] == points[(i + 1) % 4][1])
            for i in range(4)
        ):
            text.fail('UnsupportedNonrectangle', 'polygon is not a lossless axis-aligned rectangle', index + 3, 'unsupported')
        vertices = tuple((x * tick_nm, y * tick_nm) for x, y in points)
        polygons.append(Polygon(layer, index, index + 1, index + 3, tuple(points), vertices))
        index += 7
    if not polygons:
        text.fail('ResponseShapeCountMismatch', 'response requires geometry', index)
    return Response(text, actual_precision, metadata_lines, tuple(polygons), fields[3])
