def verify_backlinks(root,cache):
 count=0
 for row in cache['records']:
  assert set(row['field_sources'])==set(row)-{'field_sources'},'MissingFieldProvenance'
  for field,source in row['field_sources'].items():
   assert source['sources'] and source['derivation']
   for s in source['sources']:
    p=root/s['path'];assert sha(p)==s['sha256'],'BacklinkHashMismatch'
    if 'line_1based' in s:
     line=p.read_text().splitlines()[s['line_1based']-1];lexeme=line if s['token_0based'] is None else line.split()[s['token_0based']]
    else:
     val=read(p)
     for token in s['json_pointer'].split('/')[1:]:val=val[int(token)] if isinstance(val,list) else val[token]
     lexeme=val
    assert lexeme==s['lexeme'],('BacklinkLexemeMismatch',field,s);count+=1
 return count
